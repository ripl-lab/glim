#!/usr/bin/env bash
# Start (or attach to) this project's Claude Code container.
#
#   docker/run.sh                 # interactive shell
#   docker/run.sh claude          # start Claude Code directly
#   docker/run.sh --rebuild       # rebuild the image (also updates Claude Code)
#
# Settings are in docker/project.conf. Following the RIPL agentic coding
# standard, this repo and CODE_DIRS are editable, DATA_DIRS and REF_DIRS are
# read-only, OUTPUT_DIRS are writable and PROTECT paths are read-only. The
# agent gets docker/AGENT_RULES.md and this folder list as a managed CLAUDE.md
# that it can't edit.
#
# Every folder is mounted at its host path, so paths and Claude Code's
# per-project memory line up with the host. Claude's login is shared with
# claude-docker-temp (~/.claude-docker); a ROS workspace's build output lives
# in a named volume and survives restarts.
#
# Generated by ripl_utils/ai_agents/claude-docker-project.sh.
set -euo pipefail

DOCKER_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(dirname "$DOCKER_DIR")"

CODE_DIRS=() DATA_DIRS=() REF_DIRS=() OUTPUT_DIRS=() PROTECT=()
# shellcheck source=project.conf
source "$DOCKER_DIR/project.conf"

die()  { printf '%s: %s\n' "$NAME" "$*" >&2; exit 1; }
warn() { printf '%s: warning: %s\n' "$NAME" "$*" >&2; }
info() { printf '%s: %s\n' "$NAME" "$*" >&2; }

REBUILD=0
if [[ ${1:-} == --rebuild ]]; then REBUILD=1; shift; fi

CUSER="$(id -un)"
CHOME="/home/$CUSER"
IMAGE="$NAME-dev:u$(id -u)"
CONTAINER="$NAME-dev-$CUSER"
CONFIG_DIR="${CLAUDE_DOCKER_CONFIG:-$HOME/.claude-docker}"
PROJECT_KEY="$(printf '%s' "$REPO" | sed 's/[^a-zA-Z0-9]/-/g')"

[[ $(id -u) -ne 0 ]] || die "run this as your normal user, not root"
command -v docker >/dev/null || die "docker is not installed"

TTY=(-i)
if [[ -t 0 && -t 1 ]]; then TTY=(-it); fi

CMD="exec bash"
if (($#)); then CMD="exec $(printf '%q ' "$@")"; fi

# Already running: attach to it.
if docker ps --format '{{.Names}}' | grep -qxF "$CONTAINER"; then
  ((REBUILD == 0)) || die "stop the running container ($CONTAINER) before rebuilding"
  exec docker exec "${TTY[@]}" -w "$REPO" "$CONTAINER" bash -ic "$CMD"
fi

# ---------------------------------------------------------------------------
# Build the image if it's missing, the Dockerfile changed, or --rebuild
# ---------------------------------------------------------------------------
BUILD_HASH=$({ cat "$DOCKER_DIR/Dockerfile"; printf '%s\n' "$BASE_IMAGE" "$CUSER" "$(id -u)" "$(id -g)"; } \
  | sha256sum | cut -c1-16)
CURRENT_HASH=$(docker image inspect -f '{{ index .Config.Labels "ripl.hash" }}' "$IMAGE" 2>/dev/null || true)
if ((REBUILD)) || [[ $CURRENT_HASH != "$BUILD_HASH" ]]; then
  BUILD_FLAGS=()
  if ((REBUILD)); then BUILD_FLAGS=(--pull --no-cache); fi
  info "building image $IMAGE (first run or Dockerfile changed; this takes a few minutes)..."
  docker build "${BUILD_FLAGS[@]}" \
    --build-arg BASE_IMAGE="$BASE_IMAGE" \
    --build-arg USERNAME="$CUSER" \
    --build-arg GROUPNAME="$(id -gn)" \
    --build-arg USER_UID="$(id -u)" \
    --build-arg USER_GID="$(id -g)" \
    --label ripl.hash="$BUILD_HASH" \
    -t "$IMAGE" "$DOCKER_DIR"
fi

# ---------------------------------------------------------------------------
# Container settings
# ---------------------------------------------------------------------------
HOST_TZ="${TZ:-$(cat /etc/timezone 2>/dev/null || echo UTC)}"
ARGS=(
  --rm --init --name "$CONTAINER" --hostname "$NAME"
  --workdir "$REPO"
  -e CLAUDE_CONFIG_DIR="$CHOME/.claude"
  -e TZ="$HOST_TZ"
  -e TERM="${TERM:-xterm-256color}"
)
if [[ -n $MEM_LIMIT ]]; then ARGS+=(--memory "$MEM_LIMIT" --memory-swap "$MEM_LIMIT"); fi
if [[ -n $CPUS ]]; then ARGS+=(--cpus "$CPUS"); fi
if [[ -n $GPUS ]]; then ARGS+=(--gpus "$GPUS"); fi

if ((HOST_NETWORK)); then
  # Keep ROS discovery on this machine so nothing reaches a robot.
  ARGS+=(--network host --ipc host -e ROS_LOCALHOST_ONLY=1 -e ROS_AUTOMATIC_DISCOVERY_RANGE=LOCALHOST)
  warn "using the host network; ROS discovery is limited to this machine"
fi

# Claude's login and settings, shared with claude-docker-temp. This project's
# memory is shared with Claude on the host. Mount points are made here first
# so docker doesn't create them as root.
mkdir -p "$CONFIG_DIR/projects/$PROJECT_KEY/memory" "$HOME/.claude/projects/$PROJECT_KEY/memory"
ARGS+=(
  --mount "type=bind,source=$CONFIG_DIR,target=$CHOME/.claude"
  --mount "type=bind,source=$HOME/.claude/projects/$PROJECT_KEY/memory,target=$CHOME/.claude/projects/$PROJECT_KEY/memory"
)

if [[ -f $HOME/.gitconfig ]]; then
  ARGS+=(--mount "type=bind,source=$HOME/.gitconfig,target=$CHOME/.gitconfig,readonly")
fi

# ---------------------------------------------------------------------------
# Project folders, each at its host path
# ---------------------------------------------------------------------------
declare -A SHOWN=([code]="" [data]="" [ref]="" [output]="" [protect]="")
MOUNTED_CODE=()

add_mount() {
  local kind=$1 path=$2 abs opt
  if [[ $kind == output ]]; then mkdir -p -- "$path"; fi
  if [[ ! -e $path ]]; then
    info "skipping $kind $path (not found on this machine)"
    return 0
  fi
  abs="$(realpath -e -- "$path")"
  case "$abs" in
    *,*) die "paths containing commas aren't supported: $abs" ;;
    /|/home|"$HOME") die "refusing to mount $abs; list specific folders in project.conf" ;;
  esac
  opt="type=bind,source=$abs,target=$abs"
  case "$kind" in data|ref|protect) opt+=",readonly" ;; esac
  ARGS+=(--mount "$opt")
  SHOWN[$kind]+="- $abs"$'\n'
  if [[ $kind == code ]]; then MOUNTED_CODE+=("$abs"); fi
}

add_mount code "$REPO"
for d in "${CODE_DIRS[@]}";   do add_mount code "$d"; done
for d in "${DATA_DIRS[@]}";   do add_mount data "$d"; done
for d in "${REF_DIRS[@]}";    do add_mount ref "$d"; done
for d in "${OUTPUT_DIRS[@]}"; do add_mount output "$d"; done
for p in "${PROTECT[@]}";     do add_mount protect "$REPO/$p"; done

# ---------------------------------------------------------------------------
# Lab rules plus this session's folders, as a managed CLAUDE.md. Kept under
# CONFIG_DIR (not /tmp) so a snap-installed docker can still mount it.
# ---------------------------------------------------------------------------
mkdir -p "$CONFIG_DIR/run"
SESSION_DIR="$(mktemp -d -p "$CONFIG_DIR/run")"
trap 'rm -rf -- "$SESSION_DIR"' EXIT
{
  cat "$DOCKER_DIR/AGENT_RULES.md"
  printf '\n## Folders shared with this session\n\n'
  printf 'Only these host folders (and your Claude config) are visible.\n'
  section() { [[ -z $2 ]] || printf '\n%s:\n%s' "$1" "$2"; }
  section "Code (editable)" "${SHOWN[code]}"
  section "Data (read-only)" "${SHOWN[data]}"
  section "Reference material (read-only)" "${SHOWN[ref]}"
  section "Output / scratch (writable)" "${SHOWN[output]}"
  section "Protected (read-only; do not change in this session)" "${SHOWN[protect]}"
} > "$SESSION_DIR/CLAUDE.md"
ARGS+=(--mount "type=bind,source=$SESSION_DIR/CLAUDE.md,target=/etc/claude-code/CLAUDE.md,readonly")

# ---------------------------------------------------------------------------
# In-container setup: give back parent folders docker created as root, and
# link the code into the ROS workspace.
# ---------------------------------------------------------------------------
SETUP="true"
for d in "${MOUNTED_CODE[@]}"; do
  p="$(dirname "$d")"
  while [[ $p == "$CHOME"/* ]]; do
    SETUP+="; [ -O $(printf '%q' "$p") ] || sudo chown $(printf '%q' "$CUSER"): $(printf '%q' "$p") 2>/dev/null"
    p="$(dirname "$p")"
  done
done

if [[ -n $ROS_DISTRO ]]; then
  WS="$CHOME/${NAME}_ws"
  ARGS+=(-v "$NAME-ws-$CUSER:$WS" -e PROJECT_WS="$WS")
  SETUP+="; sudo chown $(printf '%q' "$CUSER"): $(printf '%q' "$WS"); mkdir -p $(printf '%q' "$WS/src")"
  for d in "${MOUNTED_CODE[@]}"; do
    SETUP+="; ln -sfn $(printf '%q' "$d") $(printf '%q' "$WS/src/$(basename "$d")")"
  done
fi

# Not exec'd, so the EXIT trap can remove the session's rules file.
docker run "${TTY[@]}" "${ARGS[@]}" "$IMAGE" bash -ic "$SETUP; cd $(printf '%q' "$REPO"); $CMD"
